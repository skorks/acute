# Runs chronic 0.10.2's own parse tests against acute's chronic layer. Every assertion that fails must be
# listed in differences.yml, with the rule acute follows instead. --record writes that file from this run,
# taking each rule from the corpus case for that line of test_parsing.rb, or else from the assumptions acute
# reports for the phrase; it refuses to write a difference no rule explains.
#   ruby test/chronic/run.rb [--record]
ENV["TZ"] = "America/New_York"
require "yaml"
require_relative "helper"
require_relative "../corpus"
$LOAD_PATH.unshift __dir__
require "test_parsing"
require "test_span"

module ChronicRun
  FILE = File.join(__dir__, "differences.yml")
  SOURCE = "chronic-0.10.2:test_parsing.rb:"
  # test_normalizing_day_portions calls pre_normalize, chronic's tokeniser, which acute has no counterpart for.
  # test_now_changes passes only when a second boundary falls between two parses 0.1 s apart, since acute's
  # times are whole seconds (D46).
  SKIPPED = %w[test_normalizing_day_portions test_now_changes].freeze

  module_function

  def run_tests
    reset
    [TestParsing, TestSpan].each do |klass|
      klass.public_instance_methods(false).grep(/\Atest_/).map(&:to_s).sort.each do |test|
        next if SKIPPED.include?(test)
        t = klass.new(test)
        t.setup
        t.send(test)
      rescue StandardError => e
        line = e.backtrace_locations.find { _1.path.start_with?(__dir__) && _1.label.include?(test) }&.lineno
        @checks << Check.new(test, line, @calls, nil, nil, "#{e.class}: #{e.message}")
        @calls = []
      end
    end
    checks
  end

  def show(value)
    case value
    when Chronic::Span then "#{show(value.begin)}...#{show(value.end)}"
    when Time then value.getlocal.strftime(value.subsec.zero? ? "%F %T" : "%F %T.%N")
    when nil then "nil"
    when String then value
    else value.inspect
    end
  end

  def difference(check)
    call = check.calls.last
    entry = { "test" => check.test, "line" => call&.line || check.line, "assert_line" => check.line, "phrase" => call&.text }
    entry["options"] = call.options.transform_keys(&:to_s).transform_values { _1.is_a?(Symbol) ? _1.to_s : _1 } if call && !call.options.empty?
    entry["compared_with"] = check.calls[-2].text if check.calls.size > 1
    if check.error.is_a?(String)
      entry["chronic"] = "passes"
      entry["acute"] = check.error
    else
      # chronic's tests put the parse's answer on either side of an assertion
      ours, theirs = call && check.expected.equal?(call.got) ? [check.expected, check.actual] : [check.actual, check.expected]
      entry["chronic"] = show(theirs)
      entry["acute"] = show(ours)
      entry["rule"] = "D46" if subsecond?(theirs, ours)
    end
    entry
  end

  # acute's times are whole seconds (D46)
  def subsecond?(a, b) = [a, b].all? { _1.is_a?(Time) || _1.is_a?(Numeric) } && (a.to_f - b.to_f).abs < 1

  def key(entry) = entry.values_at("test", "line", "assert_line", "phrase", "options", "compared_with")

  # The rules named by the corpus cases for the phrases compared, else those of acute's assumptions
  def rule(entry, cases)
    return entry["rule"] if entry["rule"]
    rules = entry.values_at("phrase", "compared_with").compact.flat_map do |text|
      found = cases[[entry["line"], text]] || cases.values.find { _1["text"] == text }
      found ? Corpus.rules(found) : []
    end.uniq
    if rules.empty? && entry["phrase"]
      r = Acute.parse(entry["phrase"], now: TestParsing::TIME_2006_08_16_14_00_00, zone: ENV["TZ"])
      rules = r ? r.assumptions.map(&:rule).compact.uniq : []
    end
    rules.empty? ? nil : rules.join(", ")
  end

  def main(argv)
    record = argv.delete("--record")
    checks = run_tests
    current = checks.select(&:error).map { difference(_1) }
    listed = File.exist?(FILE) ? YAML.load_file(FILE) || [] : []
    puts "chronic: #{checks.size} checks, #{checks.size - current.size} pass, #{current.size} differ"

    if record
      cases = Corpus.load(file: "chronic-tests").to_h { [[_1["source"].delete_prefix(SOURCE).to_i, _1["text"]], _1] }
      current.each { _1["rule"] = rule(_1, cases) }
      unexplained = current.reject { _1["rule"] }
      unexplained.each { puts "NO RULE: #{_1.inspect}" }
      abort "not recording: give these a rule in their corpus case's note" unless unexplained.empty?
      File.write(FILE, "# Generated by test/chronic/run.rb --record: where acute's chronic layer and chronic 0.10.2's own\n" \
                       "# tests disagree, and the rule acute follows instead. Edit the corpus notes, not this file.\n" +
                       current.sort_by { [_1["line"].to_i, _1["test"]] }.to_yaml(line_width: -1))
      puts "recorded #{current.size} differences in test/chronic/differences.yml"
      return true
    end

    old = listed.to_h { [key(_1), _1] }
    now = current.to_h { [key(_1), _1] }
    problems = now.reject { |k, e| old[k] && old[k].except("rule") == e.except("rule") }.map { |k, e| "#{old[k] ? "CHANGED" : "NEW"}: #{e.inspect}" }
    problems += (old.keys - now.keys).map { "NOW PASSES: #{old[_1].inspect}" }
    problems.each { puts _1 }
    puts "#{problems.size} not in test/chronic/differences.yml; fix them, or run test/chronic/run.rb --record" unless problems.empty?
    problems.empty?
  end
end

exit(ChronicRun.main(ARGV.dup)) if $PROGRAM_NAME == __FILE__
